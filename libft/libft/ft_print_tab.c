#include "../libft.h"

void	ft_print_tab(char **tab)
{
	int	i;

	i = 0;
	ft_printf("\n");
	while (tab[i])
	{
		ft_printf("%s", tab[i]);
		i++;
	}
	ft_printf("\n");
}
